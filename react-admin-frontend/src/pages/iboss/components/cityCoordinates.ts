/**
 * 获取城市的经纬度坐标
 * 优先级：
 * 1. 节点自身携带的有效 latitude / longitude
 * 2. GLOBAL_CITY_COORDINATES 城市匹配
 * 3. GLOBAL_COUNTRY_COORDINATES 国家匹配
 */
export function getCityCoordinates(
  countryName?: string,
  cityName?: string,
  lat?: any,
  lng?: any,
): [number, number] | null {
  const numLat = parseFloat(lat);
  const numLng = parseFloat(lng);

  if (!isNaN(numLat) && !isNaN(numLng) && (numLat !== 0 || numLng !== 0)) {
    // 经纬度校验范围: -180 <= lng <= 180, -90 <= lat <= 90
    if (numLng >= -180 && numLng <= 180 && numLat >= -90 && numLat <= 90) {
      return [numLng, numLat];
    }
  }

  const cKey = (cityName || '').trim().toLowerCase();
  if (cKey && GLOBAL_CITY_COORDINATES[cKey]) {
    return GLOBAL_CITY_COORDINATES[cKey];
  }

  // 尝试分词或模糊匹配城市
  for (const [knownCity, coords] of Object.entries(GLOBAL_CITY_COORDINATES)) {
    if (cKey.includes(knownCity) || knownCity.includes(cKey)) {
      return coords;
    }
  }

  const countryKey = (countryName || '').trim().toLowerCase();
  if (countryKey && GLOBAL_COUNTRY_COORDINATES[countryKey]) {
    return GLOBAL_COUNTRY_COORDINATES[countryKey];
  }

  for (const [knownCountry, coords] of Object.entries(GLOBAL_COUNTRY_COORDINATES)) {
    if (countryKey.includes(knownCountry) || knownCountry.includes(countryKey)) {
      return coords;
    }
  }

  return null;
}
